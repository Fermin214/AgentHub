export async function favorites(page, evidence) {
 const assert=(value,message)=>{if(!value)throw Error(message);};
 await page.locator('.nav-item').nth(1).click();
 const writer=page.locator('.skill-row').filter({has:page.getByRole('button',{name:'acceptance-writer',exact:true})});
 const second=page.locator('.skill-row').filter({has:page.getByRole('button',{name:'acceptance-second',exact:true})});
 const star=row=>row.locator('.library-actions > button').first();
 await page.evaluate(()=>{__acceptanceFaults.delayMs=2500;__acceptanceFaults.calls=[];});
 await star(writer).click();
 await page.waitForFunction(()=>document.querySelectorAll('[data-favorite-pending="true"]').length===1);
 const rect=await star(writer).boundingBox();
 await page.mouse.click(rect.x+rect.width/2,rect.y+rect.height/2,{clickCount:3});
 const pending=await page.evaluate(()=>({calls:__acceptanceFaults.calls.length,controls:[...document.querySelectorAll('.skill-row button,.page-header button')].filter(b=>!b.dataset.favoritePending).every(b=>!b.disabled&&getComputedStyle(b).opacity==='1'),cursor:getComputedStyle(document.querySelector('[data-favorite-pending]')).cursor}));
 assert(pending.calls===1&&pending.controls&&pending.cursor==='pointer','Pending isolation/deduplication');
 await page.screenshot({animations: 'disabled',path:evidence+'/native-favorite-pending.png'});
 await page.waitForFunction(()=>!document.querySelector('[data-favorite-pending]'));
 assert((await star(writer).getAttribute('aria-label')).startsWith('Remove'),'Save did not commit');
 await page.evaluate(()=>{__acceptanceFaults.delayMs=0;});
 await star(writer).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('.library-actions>button')].some(b=>b.getAttribute('aria-label')==='Add acceptance-writer to favorites'));
 await star(writer).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('.library-actions>button')].some(b=>b.getAttribute('aria-label')==='Remove acceptance-writer from favorites'));
 const roundtrip=await page.evaluate(()=>__acceptanceFaults.calls.map(c=>c.favorite));
 assert(JSON.stringify(roundtrip)==='[true,false,true]','Favorite roundtrip');
 await page.evaluate(()=>{__acceptanceFaults.failSaveOnce=true;});
 await star(second).click();
 await page.getByRole('alert').filter({hasText:'ACCEPTANCE_INJECTED: favorite save rejected'}).waitFor();
 assert(await star(second).isEnabled()&&(await star(second).getAttribute('aria-label'))==='Add acceptance-second to favorites','Failure not restored');
 await page.screenshot({animations: 'disabled',path:evidence+'/native-favorite-rejected.png'});
 await star(second).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('.library-actions>button')].some(b=>b.getAttribute('aria-label')==='Remove acceptance-second from favorites'));
 await page.evaluate(()=>{__acceptanceFaults.failRefreshOnce=true;});
 await star(second).click();
 await page.getByText(/favorite was saved, but reloading/i).waitFor();
 assert(await star(second).isEnabled()&&(await star(second).getAttribute('aria-label'))==='Add acceptance-second to favorites','Refresh failure lost save');
 await page.evaluate(()=>{__acceptanceFaults.delayMs=2000;});
 await star(writer).click(); await star(second).click();
 await page.waitForFunction(()=>document.querySelectorAll('[data-favorite-pending]').length===2);
 await page.waitForFunction(()=>!document.querySelector('[data-favorite-pending]'));
 await page.evaluate(()=>{__acceptanceFaults.delayMs=0;});
 await star(writer).click(); await star(second).click();
 await page.waitForFunction(()=>!document.querySelector('[data-favorite-pending]'));
 await page.getByRole('checkbox',{name:'Favorites only'}).check();
 await second.waitFor({state:'hidden'}); await writer.waitFor();
 await page.getByRole('checkbox',{name:'Favorites only'}).uncheck();
 await page.locator('.nav-item').first().click(); await page.locator('.nav-item').nth(1).click();
 assert((await star(writer).getAttribute('aria-label'))==='Remove acceptance-writer from favorites'&&(await star(second).getAttribute('aria-label'))==='Add acceptance-second to favorites','Navigation lost values');
 const result=await page.evaluate(async()=>{
  const snapshot=await __TAURI_INTERNALS__.invoke('dispatch',{method:'snapshot',args:{}});
  const calls=__acceptanceFaults.calls; __acceptanceFaults.restore();
  return {dataDir:snapshot.dataDir,skills:snapshot.skills.map(s=>({name:s.name,favorite:s.favorite})),calls,injectionRemoved:!window.__acceptanceFaults};
 });
 assert(result.skills.find(s=>s.name==='acceptance-writer').favorite&&!result.skills.find(s=>s.name==='acceptance-second').favorite,'Real backend values');
 return {pending,roundtrip,rejectedThenRetried:true,refreshFailureRetainedSave:true,concurrentIsolation:true,filterAndNavigation:true,...result};
}
