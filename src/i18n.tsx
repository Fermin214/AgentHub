/** A stored empty value means "follow the system", resolved once at startup. */
export function resolveLang(stored?: string): Lang {
  const value = (stored || '').trim().toLowerCase();
  if (value === 'zh' || value === 'en') return value;
  const system = typeof navigator === 'undefined' ? '' : (navigator.language || '').toLowerCase();
  return system.startsWith('zh') ? 'zh' : 'en';
}

