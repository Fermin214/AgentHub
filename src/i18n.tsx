const FORMAT = /\{(\w+)\}/g;
const fill = (text: string, vars?: Record<string, string | number>) => vars ? text.replace(FORMAT, (whole, key) => key in vars ? String(vars[key]) : whole) : text;

export type Translate = {
  (key: string, vars?: Record<string, string | number>): string;
  lang: Lang;
  locale: string;
  /** Render a backend message, falling back to the original text. */
  backend: (message: string) => string;
  /** Coarse relative time; falls back to a date once past a month. */
  relative: (iso?: string) => string;
  /** Absolute date and time in the active locale. */
  dateTime: (iso: string) => string;
  /** Locale-aware sort comparison for user-visible names. */
  compare: (a: string, b: string) => number;
};

export function makeTranslate(lang: Lang): Translate {
  const t = ((key: string, vars?: Record<string, string | number>) => {
    const entry = dictionary[key];
    if (!entry) return key;
    return fill(entry[lang], vars);
  }) as Translate;
  t.lang = lang;
  t.locale = lang === 'zh' ? 'zh-CN' : 'en-US';
  t.relative = (iso?: string) => {
    if (!iso) return '—';
    const time = new Date(iso).getTime();
    if (Number.isNaN(time)) return iso;
    const minutes = Math.floor((Date.now() - time) / 60_000);
    if (minutes < 1) return t('time.justNow');
    if (minutes < 60) return t('time.minutes', { n: minutes });
    const hours = Math.floor(minutes / 60);
    if (hours < 24) return t('time.hours', { n: hours });
    const days = Math.floor(hours / 24);
    if (days < 30) return t('time.days', { n: days });
    return new Date(iso).toLocaleDateString(t.locale);
  };
  t.dateTime = (iso: string) => new Date(iso).toLocaleString(t.locale);
  t.compare = (a: string, b: string) => a.localeCompare(b, t.locale);
  t.backend = (message: string) => {
    const trimmed = (message || '').replace(/^Error:\s*/, '').trim();
    if (trimmed.startsWith('{')) {
      try {
        const fault: unknown = JSON.parse(trimmed);
        if (fault && typeof fault === 'object' && 'code' in fault && typeof fault.code === 'string' && 'detail' in fault && typeof fault.detail === 'string') {
          const key = 'error.' + fault.code;
          if (dictionary[key]) {
            const path = 'params' in fault && fault.params && typeof fault.params === 'object' && 'path' in fault.params && typeof fault.params.path === 'string' ? fault.params.path : '';
            return t(key) + (path ? '\n' + path : '') + '\n' + fault.detail;
          }
          // Existing domain errors retain their translations during gradual migration.
          return t.backend(fault.detail);
        }
      } catch { /* Ordinary diagnostics that happen to start with a brace remain text. */ }
    }
    if (lang === 'zh') return message;
    if (backend[trimmed]) return backend[trimmed];
    // Activity names and paths are user content. Translate only the known action.
    const activity = trimmed.indexOf(' · ');
    if (activity > 0 && backend[trimmed.slice(0, activity)]) return backend[trimmed.slice(0, activity)] + ': ' + trimmed.slice(activity + 3);
    // Prefixed and suffixed core messages still translate their known part.
    for (const [zh, en] of Object.entries(backend)) {
      if (trimmed.startsWith(zh + '：') || trimmed.startsWith(zh + ': ')) return en + ' ' + trimmed.slice(zh.length + 1).trim();
    }
    return trimmed || message;
  };
  return t;
}

const LangContext = createContext<Translate>(makeTranslate('zh'));

export function LanguageProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value = useMemo(() => makeTranslate(lang), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useT = () => useContext(LangContext);
