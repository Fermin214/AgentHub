// Build a reproducible notice bundle from the Windows desktop graph and npm runtime packages.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root = process.cwd();
const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--locked', '--offline', '--format-version', '1', '--filter-platform', 'x86_64-pc-windows-msvc'], { encoding: 'utf8', maxBuffer: 30_000_000 }));
const packages = new Map(metadata.packages.map(p => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map(n => [n.id, n]));
const selected = new Map();
function visit(id, role) {
  if (selected.has(id) && (selected.get(id) === 'runtime' || role === 'build')) return;
  selected.set(id, role);
  for (const dep of nodes.get(id)?.deps ?? []) {
    for (const kind of dep.dep_kinds) {
      if (kind.kind === 'dev') continue;
      visit(dep.pkg, role === 'build' || kind.kind === 'build' ? 'build' : 'runtime');
    }
  }
}
visit(metadata.packages.find(p => p.name === 'agenthub-desktop').id, 'runtime');
const records = [];
const sections = [];
const missing = [];
function licenseFiles(dir, prefix = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    if (/^(licen[sc]e|copying|copyright|notice)([._-]|$)/i.test(entry.name)) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return licenseFiles(full, prefix + entry.name + '/');
      return [{ name: prefix + entry.name, text: fs.readFileSync(full, 'utf8') }];
    }
    return [];
  });
}
function add(record, dir) {
  let texts = licenseFiles(dir);
  const supplement = path.join(root, 'licenses', 'supplemental', record.name.replaceAll('/', '__') + '.txt');
  if (fs.existsSync(supplement)) texts.push({ name: 'verified upstream supplement', text: fs.readFileSync(supplement, 'utf8') });
  if (!texts.length) missing.push(record);
  record.notices = texts.map(t => ({ file: t.name, sha256: createHash('sha256').update(t.text).digest('hex') }));
  records.push(record);
  sections.push(`## ${record.ecosystem}: ${record.name} ${record.version}\n\nScope: ${record.role}; declared license: ${record.license}\nSource: ${record.source}\n\n` + texts.map(t => `### ${t.name}\n\n\`\`\`text\n${t.text.trim()}\n\`\`\`\n`).join('\n'));
}
for (const [id, role] of [...selected].sort(([a], [b]) => a.localeCompare(b))) {
  const p = packages.get(id);
  if (p.source) add({ ecosystem: 'cargo', name: p.name, version: p.version, role, license: p.license, source: `https://crates.io/crates/${p.name}/${p.version}` }, path.dirname(p.manifest_path));
}
const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
for (const [dir, p] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!dir || p.dev || p.optional) continue;
  const local = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  add({ ecosystem: 'npm', name: local.name, version: p.version, role: 'runtime', license: p.license ?? local.license, source: `https://www.npmjs.com/package/${local.name}/v/${p.version}` }, dir);
}
fs.mkdirSync('licenses', { recursive: true });
fs.writeFileSync('licenses/inventory.json', JSON.stringify({ schemaVersion: 1, target: 'x86_64-pc-windows-msvc', selection: 'Desktop normal + build dependencies, no CLI/dev roots; npm non-dev non-optional runtime packages. Build notices conservatively preserve generated-code attribution; build tools are not distributed.', packages: records }, null, 2) + '\n');
fs.writeFileSync('licenses/DEPENDENCY-NOTICES.md', "# AgentHub dependency license texts\n\nGenerated by scripts/release-licenses.mjs from locked Windows desktop and npm production dependencies. Runtime and build entries are identified separately; build entries do not imply distribution of those tools. Original upstream terms are preserved: OR offers a license choice, while AND requires both sets of conditions. Sources for exact component versions are linked in each entry; AgentHub does not modify their source code.\n\n" + sections.join('\n'));
console.log(JSON.stringify({ packages: records.length, missing }, null, 2));
if (missing.length) process.exitCode = 1;
